#include "init.h"

void GPIO_init(){
    BIT_SET(RCC->AHB1ENR,RCC_AHB1ENR_GPIOAEN|RCC_AHB1ENR_GPIOCEN|RCC_AHB1ENR_GPIOFEN);

    BIT_SET(GPIOA->MODER,GPIO_MODER_MODE3_0);
    BIT_SET(GPIOC->OTYPER,0x00UL);
    BIT_SET(GPIOA->OSPEEDR,GPIO_OSPEEDR_OSPEED3_0);
    BIT_SET(GPIOA->PUPDR,0x00UL);

    BIT_SET(GPIOC->MODER,GPIO_MODER_MODE0_0|GPIO_MODER_MODE3_0);
    BIT_SET(GPIOF->OTYPER,0x00UL);
    BIT_SET(GPIOC->OSPEEDR,GPIO_OSPEEDR_OSPEED0_0|GPIO_OSPEEDR_OSPEED3_0);
    BIT_SET(GPIOC->PUPDR,0x00UL);

    BIT_SET(GPIOF->MODER,GPIO_MODER_MODE3_0|GPIO_MODER_MODE5_0|GPIO_MODER_MODE10_0);
    BIT_SET(GPIOF->OTYPER,0x00UL);
    BIT_SET(GPIOF->OSPEEDR,GPIO_OSPEEDR_OSPEED3_0|GPIO_OSPEEDR_OSPEED5_0|GPIO_OSPEEDR_OSPEED10_0);
    BIT_SET(GPIOF->PUPDR,0x00UL);
}